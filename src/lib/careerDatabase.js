// ─── SMART QUESTION SELECTOR ─────────────────────────────────
export function selectQuestionsForStudent(stream, interests, count = 9) {
  const allCategories = Object.keys(questionBank);
  const priorityCategories = new Set();

  // Add stream-based categories
  const streamCats = streamCategoryMap[stream] || [];
  streamCats.forEach(c => priorityCategories.add(c));

  // Add interest-based categories
  interests.forEach(interest => {
    const cats = interestCategoryMap[interest] || [];
    cats.forEach(c => priorityCategories.add(c));
  });

  // Always include some general categories for personality insight
  const generalCats = ["leadership", "riskTaking", "teamwork", "problemSolving", "empathy"];
  generalCats.forEach(c => priorityCategories.add(c));

  const priorityList = [...priorityCategories];
  const fallbackList = allCategories.filter(c => !priorityCategories.has(c));

  const selected = [];
  const usedCategories = new Set();

  // Pick from priority categories first (max 1 per category to avoid repetition)
  const shuffled = shuffleArray([...priorityList]);
  for (const cat of shuffled) {
    if (selected.length >= count) break;
    if (questionBank[cat] && !usedCategories.has(cat)) {
      const questions = questionBank[cat];
      const randomQ = questions[Math.floor(Math.random() * questions.length)];
      selected.push(randomQ);
      usedCategories.add(cat);
    }
  }

  // Fill remaining with fallback categories
  const shuffledFallback = shuffleArray([...fallbackList]);
  for (const cat of shuffledFallback) {
    if (selected.length >= count) break;
    if (questionBank[cat] && !usedCategories.has(cat)) {
      const questions = questionBank[cat];
      const randomQ = questions[Math.floor(Math.random() * questions.length)];
      selected.push(randomQ);
      usedCategories.add(cat);
    }
  }

  return shuffleArray(selected).slice(0, count);
}

